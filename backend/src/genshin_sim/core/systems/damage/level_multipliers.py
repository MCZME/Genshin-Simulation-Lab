_TABLES = {
    TransformativeReactionSourceKind.CHARACTER: (
        CHARACTER_LEVEL_MULTIPLIER_TABLE_KEY,
        dict(enumerate(_CHARACTER_VALUES, start=1)),
    ),
    TransformativeReactionSourceKind.ENEMY_ENVIRONMENT: (
        ENEMY_ENVIRONMENT_LEVEL_MULTIPLIER_TABLE_KEY,
        dict(enumerate(_ENEMY_ENVIRONMENT_VALUES, start=1)),
    ),
}


def transformative_level_multiplier(
    source_kind: TransformativeReactionSourceKind,
    level: int,
) -> tuple[str, float]:
    """精确读取来源分类与等级对应的剧变系数。"""

    if not isinstance(source_kind, TransformativeReactionSourceKind):
        raise DamageFormulaInputError("剧变反应来源分类不受支持")
    if isinstance(level, bool) or not isinstance(level, int):
        raise DamageFormulaInputError("剧变反应来源等级必须是整数")
    table_key, table = _TABLES[source_kind]
    try:
        return table_key, table[level]
    except KeyError as exc:
        raise DamageFormulaInputError(
            f"剧变反应来源等级超出直接表范围：{source_kind.value}:{level}"
        ) from exc
